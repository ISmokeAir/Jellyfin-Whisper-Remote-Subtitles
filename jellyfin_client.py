"""
jellyfin_client.py — Jellyfin REST API wrapper and local state tracker.

Handles:
  • Fetching items without subtitles
  • Building audio download URLs
  • Uploading Base64-encoded .srt payloads
  • Persisting a processed_state.json to avoid re-processing failures
"""

import base64
import json
import logging
from pathlib import Path
from typing import Any

import requests

import config

logger = logging.getLogger(__name__)

_STATE_FILE = Path(__file__).parent / "processed_state.json"
_SESSION = requests.Session()
_SESSION.headers.update({
    "Authorization": f'MediaBrowser Token="{config.JELLYFIN_API_KEY}"',
    "Accept": "application/json",
})


# ── Local State Tracker ─────────────────────────────────────────────────────

def _load_state() -> dict[str, Any]:
    """Load the processed-items state from disk."""
    if _STATE_FILE.exists():
        try:
            content = _STATE_FILE.read_text(encoding="utf-8").strip()
            if not content:
                return {"processed": {}}
            data = json.loads(content)
            # Normalize older format entries if any exist
            processed = data.get("processed", {})
            for item_id, val in processed.items():
                if isinstance(val, dict) and "completed_langs" not in val:
                    val["completed_langs"] = []
                    # Infer completed langs from old detail string if possible
                    detail = val.get("detail", "")
                    if "langs=" in detail:
                        val["completed_langs"] = [
                            l.strip() for l in detail.split("langs=")[1].split(",") if l.strip()
                        ]
            return data
        except (json.JSONDecodeError, OSError) as exc:
            logger.warning("Corrupted state file, starting fresh: %s", exc)
    return {"processed": {}}


def _save_state(state: dict[str, Any]) -> None:
    """Persist the processed-items state to disk atomically."""
    import os
    tmp_file = _STATE_FILE.with_suffix(".tmp")
    tmp_file.write_text(json.dumps(state, indent=2, ensure_ascii=False), encoding="utf-8")
    os.replace(tmp_file, _STATE_FILE)


def mark_processed(
    item_id: str,
    status: str,
    name: str = "",
    item_type: str = "",
    completed_langs: list[str] | None = None,
    detail: str = "",
) -> None:
    """
    Record an item's Whisper transcription progress.

    status should be one of: 'success', 'failed', 'skipped', 'in_progress'
    """
    from datetime import datetime
    state = _load_state()
    existing = state["processed"].get(item_id, {})

    prev_langs = set(existing.get("completed_langs", []))
    if completed_langs:
        prev_langs.update(completed_langs)

    state["processed"][item_id] = {
        "name": name or existing.get("name", "Unknown"),
        "type": item_type or existing.get("type", "Unknown"),
        "status": status,
        "completed_langs": sorted(list(prev_langs)),
        "updated_at": datetime.now().isoformat(timespec="seconds"),
        "detail": detail,
    }
    _save_state(state)
    logger.debug("Updated item %s state: status=%s, completed_langs=%s",
                 item_id, status, sorted(list(prev_langs)))


_ISO_2_TO_3 = {
    "en": "eng", "ro": "ron", "es": "spa", "fr": "fra", "de": "deu", "it": "ita",
    "pt": "por", "ja": "jpn", "ko": "kor", "zh": "zho", "ru": "rus", "uk": "ukr",
    "pl": "pol", "nl": "nld", "tr": "tur", "hu": "hun", "cs": "ces", "el": "ell",
    "sv": "swe", "da": "dan", "fi": "fin", "nor": "no", "bg": "bul", "hr": "hrv",
    "sr": "srp", "sk": "slk", "ar": "ara", "hi": "hin",
}

_ISO_3_TO_2 = {
    "eng": "en", "ron": "ro", "rum": "ro", "spa": "es", "fra": "fr", "fre": "fr",
    "deu": "de", "ger": "de", "ita": "it", "por": "pt", "jpn": "ja", "kor": "ko",
    "zho": "zh", "chi": "zh", "rus": "ru", "ukr": "uk", "pol": "pl", "nld": "nl",
    "dut": "nl", "tur": "tr", "hun": "hu", "ces": "cs", "cze": "cs", "ell": "el",
    "gre": "el", "swe": "sv", "dan": "da", "fin": "fi", "nor": "no", "bul": "bg",
    "hrv": "hr", "srp": "sr", "slk": "sk", "slo": "sk", "ara": "ar", "hin": "hi",
}


def normalize_to_3letter(code: str) -> str:
    """Normalize a language code (2-letter or variant 3-letter) to canonical 3-letter ISO code."""
    c = code.lower().strip()
    if c in ("rum", "ron", "ro"):
        return "ron"
    if c in ("eng", "en"):
        return "eng"
    if c in _ISO_2_TO_3:
        return _ISO_2_TO_3[c]
    if c in _ISO_3_TO_2:
        return _ISO_2_TO_3.get(_ISO_3_TO_2[c], c)
    return c


def normalize_to_2letter(code: str) -> str:
    """Normalize a language code (3-letter or 2-letter) to 2-letter ISO code."""
    c = code.lower().strip()
    return _ISO_3_TO_2.get(c, c)


def get_item_pending_languages(item_id: str) -> list[str]:
    """
    Return which configured languages still need to be generated by Whisper.
    Ignores non-Whisper subtitles on the server to ensure high-quality local generation.
    """
    state = _load_state()
    entry = state.get("processed", {}).get(item_id)
    if not entry:
        return [normalize_to_3letter(l) for l in config.SUBTITLE_LANGS]

    # If permanently failed or skipped (e.g. verified no speech), no further work
    if entry.get("status") in ("failed", "skipped"):
        return []

    completed = set(normalize_to_3letter(l) for l in entry.get("completed_langs", []))
    return [normalize_to_3letter(l) for l in config.SUBTITLE_LANGS if normalize_to_3letter(l) not in completed]


def is_already_processed(item_id: str) -> bool:
    """Return True only if ALL configured target languages have been completed by Whisper."""
    return len(get_item_pending_languages(item_id)) == 0


def get_processed_state() -> dict[str, Any]:
    """Return the full processed state dict."""
    return _load_state()


# ── Jellyfin REST API ────────────────────────────────────────────────────────

def _get(endpoint: str, params: dict | None = None) -> Any:
    """Perform a GET against the Jellyfin server and return parsed JSON."""
    url = f"{config.JELLYFIN_URL}{endpoint}"
    resp = _SESSION.get(url, params=params, timeout=30)
    resp.raise_for_status()
    return resp.json()


def get_all_library_items() -> list[dict]:
    """Fetch all movies and episodes from the Jellyfin library."""
    params = {
        "Recursive": "true",
        "IncludeItemTypes": "Movie,Episode",
        "LocationTypes": "FileSystem",
        "Fields": "Path,MediaSources,MediaStreams",
    }
    data = _get("/Items", params)
    return data.get("Items", [])


def get_unsubtitled_items(limit: int = 5) -> list[dict]:
    """
    Return up to *limit* Movies or Episodes that still have pending languages
    to be generated by Whisper.
    """
    items = get_all_library_items()
    candidates: list[dict] = []
    for item in items:
        item_id = item["Id"]
        pending = get_item_pending_languages(item_id)
        if pending:
            item["_missing_languages"] = pending
            candidates.append(item)
            if len(candidates) >= limit:
                break

    logger.info("Jellyfin library scanned %d items, found %d next in queue",
                len(items), len(candidates))
    return candidates


def get_queue_summary(next_limit: int = 10) -> dict[str, Any]:
    """
    Generate an exhaustive summary of what has been done and what has to be done next.
    """
    items = get_all_library_items()
    state = _load_state()
    processed = state.get("processed", {})

    completed: list[dict] = []
    pending_queue: list[dict] = []
    failed: list[dict] = []
    skipped: list[dict] = []

    # Map items by ID for quick lookup
    item_map = {i["Id"]: i for i in items}

    for item_id, p_info in processed.items():
        st = p_info.get("status")
        entry = {
            "id": item_id,
            "name": p_info.get("name") or (get_item_display_name(item_map[item_id]) if item_id in item_map else "Unknown"),
            "completed_langs": p_info.get("completed_langs", []),
            "updated_at": p_info.get("updated_at", ""),
            "detail": p_info.get("detail", ""),
        }
        if st == "success":
            done_set = set(normalize_to_3letter(x) for x in p_info.get("completed_langs", []))
            uncompleted = [l for l in config.SUBTITLE_LANGS if normalize_to_3letter(l) not in done_set]
            if not uncompleted:
                completed.append(entry)
        elif st == "failed":
            failed.append(entry)
        elif st == "skipped":
            skipped.append(entry)

    # Now calculate pending items in queue order
    for item in items:
        item_id = item["Id"]
        pending = get_item_pending_languages(item_id)
        if pending:
            pending_queue.append({
                "id": item_id,
                "name": get_item_display_name(item),
                "type": item.get("Type", "Media"),
                "needs_languages": pending,
            })

    return {
        "total_items": len(items),
        "completed_count": len(completed),
        "pending_count": len(pending_queue),
        "failed_count": len(failed),
        "skipped_count": len(skipped),
        "completed_list": completed,
        "next_in_queue": pending_queue[:next_limit],
    }


def get_item(item_id: str) -> dict:
    """Fetch a single item from Jellyfin by ID and calculate pending languages."""
    data = _get("/Items", params={"Ids": item_id, "Fields": "Path,MediaSources,MediaStreams"})
    items = data.get("Items", [])
    if not items:
        raise ValueError(f"Item {item_id} not found on Jellyfin server")
    item = items[0]
    item["_missing_languages"] = get_item_pending_languages(item_id)
    return item


def get_item_display_name(item: dict) -> str:
    """Build a human-readable display name for a library item."""
    if item.get("Type") == "Episode":
        series = item.get("SeriesName", "Unknown Series")
        season = item.get("ParentIndexNumber", "?")
        episode = item.get("IndexNumber", "?")
        name = item.get("Name", "")
        return f"{series} S{season:02d}E{episode:02d} - {name}" if isinstance(season, int) and isinstance(episode, int) else f"{series} S{season}E{episode} - {name}"
    return item.get("Name", item.get("Id", "Unknown"))


def get_audio_stream_url(item_id: str) -> str:
    """Return the direct audio stream URL for an item."""
    return f"{config.JELLYFIN_URL}/Audio/{item_id}/stream"


def upload_subtitle(
    item_id: str,
    srt_text: str,
    language: str | None = None,
    is_default: bool | None = None,
) -> None:
    """
    Upload an SRT subtitle to Jellyfin for the given item.

    Encodes the SRT text as Base64 and POSTs to /Videos/{item_id}/Subtitles.
    Using '{lang}.whisper' (or '{lang}.whisper.default') embeds 'whisper' as the subtitle track title in Jellyfin
    (e.g., 'whisper - English - Default - SUBRIP - External'), clearly distinguishing it from
    any third-party or website-downloaded subtitles.
    When is_default is True (or matches config.DEFAULT_SUBTITLE_LANG), appending '.default' instructs
    Jellyfin to set IsDefault=True on the track, making it the primary active track while keeping older
    subtitles as fallbacks.
    """
    raw_lang = language or (config.SUBTITLE_LANGS[0] if config.SUBTITLE_LANGS else "eng")
    lang = normalize_to_3letter(raw_lang)

    if is_default is None:
        target_default = normalize_to_3letter(getattr(config, "DEFAULT_SUBTITLE_LANG", "eng"))
        is_default = (lang == target_default)

    tag = f"{lang}.whisper.default" if is_default else f"{lang}.whisper"

    encoded = base64.b64encode(srt_text.encode("utf-8")).decode("ascii")
    url = f"{config.JELLYFIN_URL}/Videos/{item_id}/Subtitles"
    payload = {
        "Language": tag,
        "Format": "srt",
        "IsForced": False,
        "Data": encoded,
    }
    resp = _SESSION.post(url, json=payload, timeout=60)
    resp.raise_for_status()
    logger.info("Uploaded subtitle for item %s (lang=%s, is_default=%s)", item_id, tag, is_default)


